ALTER TABLE public."artistLinks" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."siteSettings" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."contactRequests" ENABLE ROW LEVEL SECURITY;
