CREATE TABLE public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "openId" varchar(64) NOT NULL UNIQUE,
  name text,
  email varchar(320),
  "loginMethod" varchar(64),
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  "lastSignedIn" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.artists (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(160) NOT NULL,
  slug varchar(180) NOT NULL UNIQUE,
  biography text NOT NULL,
  genres jsonb NOT NULL DEFAULT '[]'::jsonb,
  "photoUrl" varchar(1024),
  "isPublic" boolean NOT NULL DEFAULT true,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.releases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "artistId" bigint NOT NULL REFERENCES public.artists(id) ON DELETE CASCADE,
  slug varchar(180) NOT NULL UNIQUE,
  title varchar(200) NOT NULL,
  "releaseType" text NOT NULL DEFAULT 'single' CHECK ("releaseType" IN ('single', 'ep', 'album')),
  "releaseDate" date,
  genres jsonb NOT NULL DEFAULT '[]'::jsonb,
  description text,
  "coverUrl" varchar(1024),
  "coverKey" varchar(512),
  "publicationStatus" text NOT NULL DEFAULT 'draft' CHECK ("publicationStatus" IN ('draft', 'published')),
  "distributionStatus" text NOT NULL DEFAULT 'pending' CHECK ("distributionStatus" IN ('pending', 'scheduled', 'live', 'taken_down')),
  featured boolean NOT NULL DEFAULT false,
  isrc varchar(32),
  "upcEan" varchar(32),
  "distributorName" varchar(200),
  "deliveryReference" varchar(500),
  "labelCredit" varchar(200),
  "masterOwnershipNotes" text,
  "internalNotes" text,
  "audioMasterKey" varchar(512),
  "officialVideoUrl" varchar(1024),
  "publishedAt" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public."platformLinks" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "releaseId" bigint NOT NULL REFERENCES public.releases(id) ON DELETE CASCADE,
  platform varchar(80) NOT NULL,
  url varchar(1024) NOT NULL,
  "sortOrder" integer NOT NULL DEFAULT 0,
  "isPublic" boolean NOT NULL DEFAULT false,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public."artistLinks" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "artistId" bigint NOT NULL REFERENCES public.artists(id) ON DELETE CASCADE,
  platform varchar(80) NOT NULL,
  kind text NOT NULL DEFAULT 'social' CHECK (kind IN ('streaming', 'social', 'video', 'other')),
  url varchar(1024) NOT NULL,
  "sortOrder" integer NOT NULL DEFAULT 0,
  "isPublic" boolean NOT NULL DEFAULT false
);

CREATE TABLE public."siteSettings" (
  key varchar(100) PRIMARY KEY,
  value text NOT NULL,
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public."contactRequests" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(160) NOT NULL,
  email varchar(320) NOT NULL,
  subject varchar(200) NOT NULL,
  message text NOT NULL,
  "ipHash" varchar(64) NOT NULL,
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'in_review', 'resolved')),
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

